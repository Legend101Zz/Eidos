def quantile(sorted_values, q):
    pos = q * (len(sorted_values) - 1)
    lo = math.floor(pos)
    hi = min(lo + 1, len(sorted_values) - 1)
    return sorted_values[lo] + (sorted_values[hi] - sorted_values[lo]) * (pos - lo)


@pytest.mark.parametrize("how", ["config", "task-port"])
def test_a_regression_task_is_sliced_by_rmse_and_scored_by_r2(lab, how):
    config = {"layout": "tabular", **({"task_type": "regression"} if how == "config" else {})}
    extra = {"task": {"task_type": "regression"}} if how == "task-port" else None
    data = lab.data(kind="tabular", task="regression", seed=2, predictions=True)
    res = lab.run(data, config, ("train", "validation", "predictions"), extra)
    assert res.ok, res.manifest.error
    report = res.json("report")
    y, pred = data.meta["y"], data.meta["pred"]
    assert (report["task_type"], report["task_type_source"], report["metric"]) == ("regression", "declared", "r2")
    overall = report["error_slices"]["overall"]
    resid = [p - t for p, t in zip(pred, y, strict=True)]
    assert overall["n"] == len(y)
    assert overall["rmse"] == pytest.approx(math.sqrt(sum(r * r for r in resid) / len(resid)), rel=1e-9)
    assert overall["mean_residual"] == pytest.approx(sum(resid) / len(resid), abs=1e-9)
    assert "errors" not in overall and "by_class" not in report["error_slices"]
    ordered = sorted(y)
    edges = sorted({quantile(ordered, q / 4) for q in range(5)})
    slices = report["error_slices"]["by_target_quantile"]
    assert len(slices) == len(edges) - 1 == 4
    assert sum(s["n"] for s in slices) == len(y)
    for i, got in enumerate(slices):
        lo, hi = edges[i], edges[i + 1]
        rows = [j for j, v in enumerate(y) if v >= lo and (v <= hi if i == len(slices) - 1 else v < hi)]
        assert got["n"] == len(rows) and got["low"] == pytest.approx(lo) and got["high"] == pytest.approx(hi)
        assert got["rmse"] == pytest.approx(math.sqrt(sum(resid[j] ** 2 for j in rows) / len(rows)), rel=1e-9)
    metrics = res.receipt["metrics"]
    assert metrics["baseline_validation_rmse"] == pytest.approx(overall["rmse"], rel=1e-12)
    assert metrics["reference_probe_validation_r2"] == reference(report)
    assert "reference_probe_validation_accuracy" not in metrics
    for h in report["hypotheses"]:  # the evidence is reported in R^2 units
        assert "R^2" in json.dumps(h["evidence"]), h["cause"]


