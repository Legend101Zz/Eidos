# -- error slices ------------------------------------------------------------------------------------------------------------
def error_stats(y, pred, rows):
    wrong = sum(1 for i in rows if y[i] != pred[i])
    return {"n": len(rows), "errors": wrong, "error_rate": wrong / len(rows)}


def test_the_error_rate_uses_predictions_matched_by_id_not_by_position(lab):
    res, report, data = lab.diagnose(kind="sequence", seed=2, predictions=True, ports=("train", "validation", "predictions"))
    y, pred = data.meta["y"], data.meta["pred"]
    n = len(y)
    expected = error_stats(y, pred, range(n))
    assert 0 < expected["errors"] < n
    # the file lists the ids in reverse: reading it by position would have given a different rate
    assert sum(1 for a, b in zip(y, data.meta["pred_file_order"], strict=True) if a != b) != expected["errors"]
    overall = report["error_slices"]["overall"]
    assert overall["n"] == n and overall["errors"] == expected["errors"]
    assert overall["error_rate"] == pytest.approx(expected["error_rate"], abs=1e-12)
    assert "input port predictions" in report["error_slices"]["source"]
    assert res.receipt["metrics"]["baseline_validation_error_rate"] == pytest.approx(expected["error_rate"], abs=1e-12)


def test_the_error_slices_by_class_and_confusion_add_up(lab):
    _, report, data = lab.diagnose(kind="sequence", seed=2, predictions=True, ports=("train", "validation", "predictions"))
    y, pred = data.meta["y"], data.meta["pred"]
    slices = report["error_slices"]
    by_class = slices["by_class"]
    assert sorted(by_class) == ["0", "1", "2"]
    for c in (0, 1, 2):
        rows = [i for i, v in enumerate(y) if v == c]
        want = error_stats(y, pred, rows)
        assert by_class[str(c)]["n"] == want["n"] and by_class[str(c)]["errors"] == want["errors"]
        assert by_class[str(c)]["error_rate"] == pytest.approx(want["error_rate"], abs=1e-12)
    assert sum(s["n"] for s in by_class.values()) == len(y)
    assert sum(s["errors"] for s in by_class.values()) == slices["overall"]["errors"]
    # three classes have six wrong (true, predicted) pairs, so the top-ten confusion list is complete
    confusions = Counter((a, b) for a, b in zip(y, pred, strict=True) if a != b)
    listed = {(int(c["true"]), int(c["predicted"])): c["count"] for c in slices["top_confusions"]}
    assert listed == dict(confusions)
    assert [c["count"] for c in slices["top_confusions"]] == sorted(confusions.values(), reverse=True)
    for name in ("by_input_norm_quantile", "by_input_mean_quantile"):
        assert sum(s["n"] for s in slices[name]) == len(y), name
        assert sum(s["errors"] for s in slices[name]) == slices["overall"]["errors"], name
        assert all(s["low"] <= s["high"] for s in slices[name])


