"""Pydantic v2 boundary models for the worker wire contract (``eidos-wire/<major>``).

These models are the server-side source of truth for the published JSON Schemas in
``schemas/eidos-wire/v<major>/`` (generated by ``scripts/dev/gen_wire_schemas.py``). They mirror the
standard-library dataclasses in ``eidos_wire`` (which the worker packages use, so workers never need
pydantic v2); ``tests/unit/test_wire_schemas.py`` keeps the two in sync.

Layers on receipt (server side):

1. structural: :func:`validate_wire` checks a message against these models (field types, enums,
   patterns, required fields). Unknown fields are accepted and ignored, as the wire promises for a
   newer minor version.
2. semantic: ``eidos_wire`` ``from_dict`` / ``parse_manifest`` keep the rules a JSON Schema cannot
   express (duplicate output slots, kind/phase combinations, ``..`` path parts after normalisation).
"""

from __future__ import annotations

from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError

from eidos_wire import WIRE_MAJOR, WIRE_SCHEMA, canonical_json
from eidos_wire.manifest import _CAPABILITY, _ID, _SEMVER

JSON_SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
GENERATOR = "scripts/dev/gen_wire_schemas.py"
WIRE_PATTERN = rf"^eidos-wire/{WIRE_MAJOR}(\.[0-9]+)*$"
# Relative to the staging directory: not absolute, no backslash, no '..' path segment, not empty.
SAFE_FILENAME = r"^(?!/)(?!.*\\)(?!(?:.*/)?\.\.(?:/|$)).+$"
ENTRY_PATTERN = r"^[^:].*:.*[^:]$"

_CONFIG = ConfigDict(strict=True, extra="ignore", regex_engine="python-re", populate_by_name=True)

Wire = Annotated[str, Field(pattern=WIRE_PATTERN, description="Wire contract identity, 'eidos-wire/<major>'.")]
Capability = Annotated[str, Field(pattern=_CAPABILITY.pattern)]
JsonObject = dict[str, Any]


class InputBinding(BaseModel):
    """One immutable input artifact made available read-only to the worker."""

    model_config = _CONFIG
    artifact_id: str
    digest: str
    path: str
    media_type: str = "application/octet-stream"
    schema_: str | None = Field(default=None, alias="schema")
    size: Annotated[int, Field(ge=0)] | None = None


class ComponentRef(BaseModel):
    """The component the attempt runs (``id``, ``entry``; also release, digest, kind, implements...)."""

    model_config = _CONFIG
    id: str
    entry: Annotated[str, Field(pattern=ENTRY_PATTERN, description="'module:function'")]


class LlmGrant(BaseModel):
    """A scoped, short-lived, budget-limited LLM grant for one attempt (ADR 0013). A grant token, never a key."""

    model_config = _CONFIG
    grant_id: str
    token: Annotated[str, Field(min_length=16)]
    socket: str = Field(description="path of the broker's Unix socket inside the worker's view")
    models: Annotated[list[str], Field(min_length=1)]
    max_requests: Annotated[int, Field(ge=1)]
    max_tokens: Annotated[int, Field(ge=1)]
    max_usd: float | None = None
    expires_at: str


class Invocation(BaseModel):
    """Everything a worker may know about one attempt. Written by the trusted launcher (server to worker)."""

    model_config = _CONFIG
    job_id: str
    attempt_id: str
    epoch: Annotated[int, Field(ge=1)]
    project_id: str
    component: ComponentRef
    inputs: dict[str, InputBinding]
    config: JsonObject
    staging_dir: str
    scratch_dir: str
    limits: JsonObject = Field(default_factory=dict)
    ports: JsonObject = Field(default_factory=dict)
    seed: int | None = None
    wire: Wire
    llm_grant: LlmGrant | None = None


class OutputEntry(BaseModel):
    """One staged output file. ``filename`` is relative to the staging directory."""

    model_config = _CONFIG
    slot: str
    filename: Annotated[str, Field(pattern=SAFE_FILENAME)]
    digest: str
    size: Annotated[int, Field(ge=0)]
    media_type: str = "application/octet-stream"
    schema_: str | None = Field(default=None, alias="schema")
    role: str = Field(default="output", description="output | checkpoint | model-export | log | context")


class OutputManifest(BaseModel):
    """The worker's claim about what it produced (worker to server). Verified by the launcher, fenced by the server."""

    model_config = _CONFIG
    job_id: str
    attempt_id: str
    epoch: Annotated[int, Field(ge=1)]
    status: Literal["succeeded", "failed"]
    outputs: list[OutputEntry] = Field(default_factory=list)
    receipt: JsonObject = Field(default_factory=dict)
    error: JsonObject | None = None
    wire: Wire


Kind = Literal["artifact-op", "training-extension", "decision-policy", "provider", "planning", "assessment"]
Effect = Literal["observe", "generate-data", "change-weights", "change-learning", "change-structure", "plan", "assess"]
Phase = Literal[
    "before-model-construction",
    "after-model-construction",
    "before-optimizer-construction",
    "after-backward",
    "after-gradient-unscale",
    "before-optimizer-step",
    "after-optimizer-step",
    "on-checkpoint-save",
    "on-checkpoint-load",
    "on-evaluation",
]
Isolation = Literal["immutable-artifacts", "private-copy", "in-trial", "sealed"]
InputPort = Annotated[str, Field(pattern=rf"{_CAPABILITY.pattern}|^\*$")]


class LlmUse(BaseModel):
    """Specialist model use declared by a component (role, prompt revision, limits)."""

    model_config = _CONFIG
    role: Any
    prompt_revision: Any
    max_calls: Any
    max_tokens: Any
    models: list[str] | None = None  # optional narrowing of the project's broker allowlist (ADR 0013)
    max_usd: float | None = None


class ComponentManifest(BaseModel):
    """Component manifest ``eidos-component.json`` (author to server; design "The component contract")."""

    model_config = _CONFIG
    id: Annotated[str, Field(pattern=_ID.pattern)]
    release: Annotated[str, Field(pattern=_SEMVER.pattern)]
    implements: Capability
    kind: Kind
    entry: Annotated[str, Field(pattern=ENTRY_PATTERN)]
    scientific_effects: Annotated[list[Effect], Field(min_length=1)]
    input: dict[str, InputPort] = Field(default_factory=dict)
    output: dict[str, Capability] = Field(default_factory=dict)
    requires: list[Capability] = Field(default_factory=list)
    optional: list[Capability] = Field(default_factory=list)
    reads: list[str] = Field(default_factory=list)
    writes: list[str] = Field(default_factory=list)
    isolation: Isolation = "immutable-artifacts"
    card: str | None = None
    controls: list[str] = Field(default_factory=list)
    receipt: list[str] = Field(default_factory=list)
    phases: list[Phase] = Field(default_factory=list)
    state: JsonObject = Field(default_factory=dict)
    cost: JsonObject = Field(default_factory=dict)
    grants: list[str] = Field(default_factory=list)
    metrics: JsonObject = Field(default_factory=dict)
    conflicts: list[str] = Field(default_factory=list)
    llm: LlmUse | None = None
    python: str = ">=3.9"
    wire: Wire = WIRE_SCHEMA
    dependencies: list[str] = Field(default_factory=list)
    license: str | None = None


# -- recorded research records (not worker messages; published alongside them) ------------------------------------
ClaimState = Literal["protocol-passed", "candidate-submitted", "not-supported", "abstained", "null-reported", "no-claim"]
Disposition = Literal["confirmed", "candidate", "null", "abstain"]


class ConclusionClaim(BaseModel):
    """The claim state of a conclusion: derived from recorded evidence and assessor state (ADR 0021), never from a
    model's chosen status. ``confirmed`` is true only with a conformant, healthy assessor pass."""

    model_config = _CONFIG

    schema_: Literal["conclusion-claim/1"] = Field(alias="schema")
    state: ClaimState
    confirmed: bool
    label: str
    requested_disposition: Disposition | None = None
    claim_id: str | None = None
    claim_revision: int | None = None
    statement: str | None = None
    assessment_id: str | None = None
    plan_id: str | None = None
    success_rule_ref: str | None = None
    scope: Any = None
    point_estimate: JsonObject | None = None
    uncertainty: Any = None
    population: Any = None
    unfulfilled_obligations: list[str] = Field(default_factory=list)
    evidence_refs: list[str] = Field(default_factory=list)
    assessments_considered: list[JsonObject] = Field(default_factory=list)
    downgraded_from: Disposition | None = None
    downgrade_reason: str | None = None
    remaining_alternatives: list[Any] = Field(default_factory=list)


class Conclusion(BaseModel):
    """An investigation's recorded conclusion. Records from before ADR 0021 have no ``schema`` or ``claim_state``."""

    model_config = _CONFIG

    schema_: Literal["conclusion/2"] | None = Field(default=None, alias="schema")
    turn_id: str
    summary: str
    scope: Any = None
    action: Literal["conclude", "stop"]
    claim_state: ConclusionClaim | None = None


#: Published message and manifest types: schema file stem -> boundary model.
MESSAGES: dict[str, type[BaseModel]] = {
    "invocation": Invocation,
    "output-manifest": OutputManifest,
    "component-manifest": ComponentManifest,
}


#: Ledger records published with the wire schemas; not worker messages, so outside ``MESSAGES``.
RECORDS: dict[str, type[BaseModel]] = {"conclusion": Conclusion}
#: Every schema file: schema file stem -> boundary model.
PUBLISHED: dict[str, type[BaseModel]] = {**MESSAGES, **RECORDS}


class WireSchemaError(ValueError):
    """A received message violates the published wire JSON Schema. ``problems`` lists each violation."""

    def __init__(self, kind: str, problems: list[str]):
        super().__init__(f"{kind} violates the {WIRE_SCHEMA} schema: " + "; ".join(problems))
        self.kind = kind
        self.problems = problems


def schema_document(name: str) -> dict[str, Any]:
    """The JSON Schema (2020-12) for one published message type, with the generator header."""
    model = PUBLISHED[name]
    body = model.model_json_schema(by_alias=True, mode="validation")
    return {
        "$schema": JSON_SCHEMA_DIALECT,
        "$id": f"urn:eidos:schema:eidos-wire:v{WIRE_MAJOR}:{name}",
        **body,
        "x-eidos": {
            "generator": GENERATOR,
            "source": f"{model.__module__}.{model.__qualname__}",
            "wire": WIRE_SCHEMA,
            "wire_major": WIRE_MAJOR,
            "unknown_fields": "accepted and ignored (newer minor versions add optional fields)",
        },
    }


def validate_wire(name: str, data: Any) -> None:
    """Raise :class:`WireSchemaError` unless ``data`` (a decoded JSON message) satisfies the schema."""
    model = PUBLISHED[name]
    try:
        text = canonical_json(data)
    except (TypeError, ValueError) as exc:
        raise WireSchemaError(name, [f"<message>: not strict JSON ({exc})"]) from None
    try:
        model.model_validate_json(text)
    except ValidationError as exc:
        problems = [
            f"{'.'.join(str(p) for p in err['loc']) or '<message>'}: {err['msg']}" for err in exc.errors()
        ]
        raise WireSchemaError(name, problems) from None
